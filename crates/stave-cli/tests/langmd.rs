//! LANG.md examples as tests. Every ```stave block of LANG.md is a complete source
//! file (LANG.md §5). This test extracts them, in order, to `tests/conformance/langmd/block_<n>.stv`
//! (checked in: a stale, missing, or extra file fails; `STAVE_BLESS=1` rewrites them) and tests each
//! per `tests/conformance/langmd/manifest.toml` (`mode = check|build|run`, `target`, `needs`,
//! `stdout`). Each file starts with a generated header whose conformance annotations match its
//! manifest entry (`CHECK-ONLY`, `STDOUT`, or `PARSE-ONLY` for a block with `needs`), so
//! `stave test tests/conformance` runs them as well.

use std::path::{Path, PathBuf};
use std::process::Command;

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn dir() -> PathBuf {
    repo().join("tests/conformance/langmd")
}

/// The ```stave blocks of `md`, each with a final newline.
fn blocks(md: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur: Option<Vec<&str>> = None;
    for l in md.lines() {
        match &mut cur {
            None if l.trim() == "```stave" => cur = Some(Vec::new()),
            None => {}
            Some(_) if l.trim() == "```" => {
                let b = cur.take().unwrap_or_default();
                out.push(format!("{}\n", b.join("\n")));
            }
            Some(b) => b.push(l),
        }
    }
    assert!(cur.is_none(), "unterminated ```stave block in LANG.md");
    out
}

#[derive(Debug)]
struct Entry {
    n: usize,
    mode: String,
    target: Option<String>,
    /// The stage0 feature the block waits for; the block is only parsed until it is removed.
    needs: Option<String>,
    stdout: Option<String>,
}

fn manifest() -> Vec<Entry> {
    let text = std::fs::read_to_string(dir().join("manifest.toml")).unwrap();
    let v: toml::Table = toml::from_str(&text).unwrap();
    let mut entries = Vec::new();
    for b in v["block"].as_array().expect("[[block]]") {
        let t = b.as_table().unwrap();
        for k in t.keys() {
            assert!(["n", "mode", "target", "needs", "stdout"].contains(&k.as_str()), "unknown key {k}");
        }
        let s = |k: &str| t.get(k).map(|x| x.as_str().unwrap_or_else(|| panic!("{k}: a string")).to_string());
        let e = Entry {
            n: t["n"].as_integer().expect("n") as usize,
            mode: s("mode").expect("mode"),
            target: s("target"),
            needs: s("needs"),
            stdout: s("stdout"),
        };
        assert!(["check", "build", "run"].contains(&e.mode.as_str()), "block {}: mode {}", e.n, e.mode);
        assert_eq!(e.stdout.is_some(), e.mode == "run", "block {}: `stdout` exactly for run", e.n);
        entries.push(e);
    }
    entries
}

fn enabled(e: &Entry) -> bool {
    e.needs.is_none()
}

/// The checked-in file for block `n`: the generated header, then the block.
fn file_text(e: &Entry, block: &str) -> String {
    let mut h = format!(
        "// LANG.md block {}: generated by crates/stave-cli/tests/langmd.rs (STAVE_BLESS=1); do not edit.\n",
        e.n
    );
    if !enabled(e) {
        h.push_str("//~ PARSE-ONLY\n");
    } else {
        match (e.mode.as_str(), &e.stdout) {
            ("check", _) => h.push_str("//~ CHECK-ONLY\n"),
            ("run", Some(f)) => h.push_str(&format!("//~ STDOUT {f}\n")),
            _ => {}
        }
        if let Some(t) = &e.target {
            h.push_str(&format!("//~ TARGET {t}\n"));
        }
    }
    h + block
}

#[test]
fn langmd_blocks_are_extracted() {
    let md = std::fs::read_to_string(repo().join("LANG.md")).unwrap();
    let bs = blocks(&md);
    assert!(bs.len() >= 5, "LANG.md has {} Stave blocks", bs.len());
    let entries = manifest();
    let ns: Vec<usize> = entries.iter().map(|e| e.n).collect();
    assert_eq!(ns, (0..bs.len()).collect::<Vec<_>>(), "one manifest entry per block, in order");
    let bless = std::env::var("STAVE_BLESS").is_ok_and(|v| v == "1");
    let mut stale = Vec::new();
    for (e, b) in entries.iter().zip(&bs) {
        assert!(!b.contains("..\n") && !b.contains("{ .. }"), "block {}: a placeholder", e.n);
        let p = dir().join(format!("block_{}.stv", e.n));
        let want = file_text(e, b);
        if std::fs::read_to_string(&p).ok().as_deref() != Some(want.as_str()) {
            if bless {
                std::fs::write(&p, &want).unwrap();
            } else {
                stale.push(p.display().to_string());
            }
        }
    }
    // No file for a block that no longer exists.
    for f in std::fs::read_dir(dir()).unwrap() {
        let name = f.unwrap().file_name().to_string_lossy().into_owned();
        if let Some(n) = name.strip_prefix("block_").and_then(|s| s.strip_suffix(".stv")) {
            let n: usize = n.parse().unwrap_or(usize::MAX);
            assert!(n < bs.len(), "{name}: LANG.md has no block {n}");
        }
    }
    assert!(stale.is_empty(), "stale LANG.md extracts (rerun with STAVE_BLESS=1): {stale:?}");
}

fn stave(args: &[&str], cwd: &Path) -> (i32, String, String) {
    let o = Command::new(env!("CARGO_BIN_EXE_stave"))
        .args(args)
        .current_dir(cwd)
        .env_remove("STAVE_STD_DIR")
        .env_remove("STAVE_THREADS")
        .output()
        .unwrap();
    (
        o.status.code().unwrap_or(-1),
        String::from_utf8_lossy(&o.stdout).into(),
        String::from_utf8_lossy(&o.stderr).into(),
    )
}

#[test]
fn langmd_blocks_check_build_and_run() {
    let entries = manifest();
    let tmp = Path::new(env!("CARGO_TARGET_TMPDIR")).join("langmd");
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(&tmp).unwrap();
    let host_runs = cfg!(all(target_os = "linux", any(target_arch = "x86_64", target_arch = "aarch64")));
    let mut fails = Vec::new();
    for e in &entries {
        let src = dir().join(format!("block_{}.stv", e.n)).display().to_string();
        if !enabled(e) {
            // Waiting on a stage0 feature: it only has to parse.
            let (c, _, err) = stave(&["test", &src], &tmp);
            if c != 0 {
                fails.push(format!("block {} (parse only): {err}", e.n));
            }
            continue;
        }
        let mut args = vec![if e.mode == "check" { "check" } else { "build" }, src.as_str()];
        let out = tmp.join(format!("block_{}", e.n)).display().to_string();
        if e.mode != "check" {
            args.extend(["-o", out.as_str()]);
        }
        if let Some(t) = &e.target {
            args.extend(["--target", t.as_str()]);
        }
        let (c, _, err) = stave(&args, &tmp);
        if c != 0 {
            fails.push(format!("block {} ({}): exit {c}\n{err}", e.n, e.mode));
            continue;
        }
        if e.mode == "run" && host_runs && e.target.is_none() {
            let o = Command::new(&out).output().unwrap();
            let want = std::fs::read(dir().join(e.stdout.as_ref().unwrap())).unwrap();
            if o.status.code() != Some(0) || o.stdout != want {
                fails.push(format!(
                    "block {}: run gave {:?}, stdout {:?}, want {:?}",
                    e.n,
                    o.status.code(),
                    String::from_utf8_lossy(&o.stdout),
                    String::from_utf8_lossy(&want)
                ));
            }
        }
    }
    assert!(fails.is_empty(), "{}", fails.join("\n"));
}
