//! The Stave syntax layer: lexer, bracket check and item finder,
//! table-driven LL(1) parser, AST, and pretty-printer.
//!
//! Pipeline for one file (each stage is also usable on its own):
//! 1. [`lex`]: bytes → [`Token`]s (`kind: u8`, `start: u32`) + lexical diagnostics
//!    (E0001–E0003, E0006, E0015, E0017, E0018). Token kinds are the generated terminal ids
//!    ([`generated::terminals::Term`]) plus [`KIND_ERROR`]. Token ends are not stored:
//!    [`token_end`] / [`token_text`] re-lex one token.
//! 2. [`items`]: bracket check (E0016, E0005) and the item cut → [`ItemTable`].
//! 3. [`parse_items`] / [`parse_item`]: the PDA over `generated::ll1_table`, one item at a time,
//!    in parallel → per-item postorder [`Node`]s or the item's first syntax error.
//! 4. [`parse_file`] runs all three and returns a [`ParsedFile`]; [`ParsedFile::item_ast`] gives
//!    an [`ItemAst`] view with child accessors.
//! 5. [`print_file`]: the pretty-printer; its output re-parses to the same tokens and AST.
//!
//! Every function is total: no input makes it panic (the fuzz targets in `fuzz/` check this).
//! Diagnostics are built only through `stave_diag::Diagnostic::new` from the registry templates.

/// LL(1) tables generated by `tools/ll1gen` from `contracts/grammar.ebnf` (not rustfmt-formatted).
