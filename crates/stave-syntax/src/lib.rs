/// Maps a file into memory for [`lex`] / [`parse_file`].
/// An empty file maps to an empty buffer.
pub fn map_file(path: &std::path::Path) -> std::io::Result<SourceBytes> {
    let f = std::fs::File::open(path)?;
    if f.metadata()?.len() == 0 {
        return Ok(SourceBytes::Empty);
    }
    // SAFETY: the map is read-only and the compiler never writes its inputs. Another process may
    // still change the file while it is mapped, which breaks the immutability a `&[u8]` promises
    // (memmap2's documented caveat); the stages only read the bytes and are total over arbitrary
    // bytes, so the build sees a mix of old and new contents. A file
    // truncated below the mapped length is not: touching a page past the new end raises SIGBUS,
    // which kills the compiler with no diagnostic and bypasses the exit-3 panic handler. That
    // risk is accepted for sources being edited during a build.
    let m = unsafe { memmap2::Mmap::map(&f)? };
    Ok(SourceBytes::Mapped(m))
}

/// File contents from [`map_file`].
pub enum SourceBytes {
    Empty,
    Mapped(memmap2::Mmap),
}

impl std::ops::Deref for SourceBytes {
    type Target = [u8];

    fn deref(&self) -> &[u8] {
        match self {
            SourceBytes::Empty => &[],
            SourceBytes::Mapped(m) => m,
        }
    }
}

/// Builds a located diagnostic from its registry templates. A template failure is a compiler bug:
/// it panics in debug builds and drops the diagnostic in release builds.
pub(crate) fn make_diag(
    code: &str,
    case: Option<&str>,
    holes: &[(&str, &str)],
    primary: stave_diag::Span,
    roles: &[(&str, stave_diag::Span)],
) -> Option<stave_diag::Diagnostic> {
    match stave_diag::Diagnostic::new(code, case, holes, Some(primary), roles) {
        Ok(d) => Some(d),
        Err(e) => {
            if cfg!(debug_assertions) {
                panic!("stave-syntax: cannot build {code}: {e}");
            }
            None
        }
    }
}
