//! The intrinsic table (`crates/stave-ir/tables/intrinsics.toml`): stave-ir's
//! (`crates/stave-ir/src/generated/intrinsic_table.rs`, included by `intrinsics.rs`) and stage1's
//! (`stage1/ir/src/generated/intrinsic_table.stv`), so the front end, stage0's verifier, and
//! stage1's verifier read one list of names, arches, and signatures.

use std::fmt::Write;

use serde::Deserialize;

use crate::known::ITYS;

pub const TABLE: &str = "crates/stave-ir/tables/intrinsics.toml";
pub const RUST_OUT: &str = "crates/stave-ir/src/generated/intrinsic_table.rs";
pub const STAVE_OUT: &str = "stage1/ir/src/generated/intrinsic_table.stv";

const ARCHES: [(&str, &str); 3] = [("x86", "X86"), ("a64", "A64"), ("both", "Both")];

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawTable {
    intrinsic: Vec<Entry>,
    ptx: Ptx,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Entry {
    name: String,
    kind: String,
    arch: String,
    #[serde(default)]
    params: Option<Vec<String>>,
    #[serde(default)]
    ret: Option<String>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Ptx {
    names: Vec<String>,
    prefixes: Vec<String>,
    suffixes: Vec<String>,
}

fn ity(name: &str) -> Result<usize, String> {
    ITYS.iter().position(|t| t.0 == name).ok_or_else(|| format!("{TABLE}: unknown type `{name}`"))
}

fn arch(name: &str) -> Result<usize, String> {
    ARCHES.iter().position(|a| a.0 == name).ok_or_else(|| format!("{TABLE}: unknown arch `{name}`"))
}

/// Parses and checks the table: names unique, of the `Intr` shape (`[a-z0-9_]+`), sorted by bytes
/// in the output; `params` and `ret` both present or both absent; known types and arches.
fn parse(text: &str) -> Result<RawTable, String> {
    let mut t: RawTable = toml::from_str(text).map_err(|e| format!("{TABLE}: {e}"))?;
    for e in &t.intrinsic {
        let n = &e.name;
        if n.is_empty() || !n.bytes().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'_') {
            return Err(format!("{TABLE}: `{n}` is not an intrinsic name"));
        }
        if e.params.is_some() != e.ret.is_some() {
            return Err(format!("{TABLE}: `{n}` has one of `params` and `ret` without the other"));
        }
        arch(&e.arch)?;
        for p in e.params.iter().flatten() {
            ity(p)?;
        }
        if let Some(r) = &e.ret {
            ity(r)?;
        }
    }
    t.intrinsic.sort_by(|a, b| a.name.as_bytes().cmp(b.name.as_bytes()));
    if let Some(w) = t.intrinsic.windows(2).find(|w| w[0].name == w[1].name) {
        return Err(format!("{TABLE}: `{}` twice", w[0].name));
    }
    Ok(t)
}

const HEADER: &str = "generated by tools/gen-tables from crates/stave-ir/tables/intrinsics.toml; do not edit";

fn quoted(xs: &[String]) -> String {
    xs.iter().map(|x| format!("\"{x}\"")).collect::<Vec<_>>().join(", ")
}

fn emit_rust(t: &RawTable) -> Result<String, String> {
    let mut o = format!(
        "// {HEADER}\n// The intrinsic table by name (bytes order) and the PTX set (`intrinsics.rs` includes this file).\n\n"
    );
    let _ = writeln!(o, "const TABLE: [Entry; {}] = [", t.intrinsic.len());
    for e in &t.intrinsic {
        let sig = match (&e.params, &e.ret) {
            (Some(ps), Some(r)) => {
                let ps: Vec<String> = ps
                    .iter()
                    .map(|p| ity(p).map(|i| format!("ITy::{}", ITYS[i].1)))
                    .collect::<Result<_, _>>()?;
                format!("Some((&[{}], ITy::{}))", ps.join(", "), ITYS[ity(r)?].1)
            }
            _ => "None".to_string(),
        };
        let _ = writeln!(
            o,
            "    Entry {{ name: \"{}\", kind: Kind::{}, arch: IArch::{}, sig: {sig} }},",
            e.name,
            e.kind,
            ARCHES[arch(&e.arch)?].1
        );
    }
    o += "];\n\n";
    let p = &t.ptx;
    let _ = writeln!(o, "const PTX_NAMES: [&str; {}] = [{}];", p.names.len(), quoted(&p.names));
    let _ = writeln!(o, "const PTX_PREFIXES: [&str; {}] = [{}];", p.prefixes.len(), quoted(&p.prefixes));
    let _ = writeln!(o, "const PTX_SUFFIXES: [&str; {}] = [{}];", p.suffixes.len(), quoted(&p.suffixes));
    Ok(o)
}

fn pack(xs: &[String]) -> String {
    let (indent, width) = ("    ", 100);
    let mut out = String::new();
    let mut line = String::new();
    for it in xs {
        if !line.is_empty() && indent.len() + line.len() + it.len() + 2 > width {
            out += indent;
            out += line.trim_end();
            out.push('\n');
            line.clear();
        }
        line += it;
        line += ", ";
    }
    if !line.is_empty() {
        out += indent;
        out += line.trim_end();
        out.push('\n');
    }
    out
}

fn array(o: &mut String, name: &str, ty: &str, xs: &[String]) {
    let _ = writeln!(o, "pub const {name}: [{ty}; {}] = [", xs.len());
    *o += &pack(xs);
    *o += "];\n";
}

fn strings(o: &mut String, name: &str, ss: &[String]) {
    let mut off = vec!["0".to_string()];
    let mut bytes = Vec::new();
    for s in ss {
        bytes.extend(s.bytes().map(|b| b.to_string()));
        off.push(bytes.len().to_string());
    }
    array(o, &format!("{name}_OFF"), "u32", &off);
    array(o, name, "u8", &bytes);
}

fn emit_stave(t: &RawTable) -> Result<String, String> {
    let mut o = format!("// {HEADER}\n");
    o += "// The intrinsic table by row, names in bytes order: name i (ASCII) is\n";
    o += "// INTR_NAME[INTR_NAME_OFF[i]..INTR_NAME_OFF[i + 1]], its arch INTR_ARCH (`ARCH_*`), its result\n";
    o += "// INTR_RET (`known_items.ITY_*`; `known_items.ITY_NONE`: no checked signature), its params\n";
    o += "// INTR_PARAM[INTR_PARAM_OFF[i]..INTR_PARAM_OFF[i + 1]]. INTR_STATIC_ADDR and\n";
    o += "// INTR_CPU_BASELINE are the rows of the kinds `StaticAddr` and `CpuBaseline`. The PTX set: the\n";
    o += "// PTX_NAME rows, and every name with a PTX_PREFIX row as prefix and a PTX_SUFFIX row as suffix.\n\n";
    for (k, (name, _)) in ARCHES.iter().enumerate() {
        let _ = writeln!(o, "pub const ARCH_{}: u8 = {k};", name.to_ascii_uppercase());
    }
    let row = |kind: &str| t.intrinsic.iter().position(|e| e.kind == kind);
    let sa = row("StaticAddr").ok_or_else(|| format!("{TABLE}: no `StaticAddr` row"))?;
    let cb = row("CpuBaseline").ok_or_else(|| format!("{TABLE}: no `CpuBaseline` row"))?;
    let _ = writeln!(o, "pub const INTR_N: usize = {};", t.intrinsic.len());
    let _ = writeln!(o, "pub const INTR_STATIC_ADDR: u32 = {sa};");
    let _ = writeln!(o, "pub const INTR_CPU_BASELINE: u32 = {cb};");
    let names: Vec<String> = t.intrinsic.iter().map(|e| e.name.clone()).collect();
    strings(&mut o, "INTR_NAME", &names);
    let arches: Vec<String> =
        t.intrinsic.iter().map(|e| arch(&e.arch).map(|a| a.to_string())).collect::<Result<_, _>>()?;
    array(&mut o, "INTR_ARCH", "u8", &arches);
    let mut rets = Vec::new();
    let mut poff = vec!["0".to_string()];
    let mut params = Vec::new();
    for e in &t.intrinsic {
        rets.push(match &e.ret {
            Some(r) => ity(r)?.to_string(),
            None => "255".to_string(),
        });
        for p in e.params.iter().flatten() {
            params.push(ity(p)?.to_string());
        }
        poff.push(params.len().to_string());
    }
    array(&mut o, "INTR_RET", "u8", &rets);
    array(&mut o, "INTR_PARAM_OFF", "u32", &poff);
    array(&mut o, "INTR_PARAM", "u8", &params);
    strings(&mut o, "PTX_NAME", &t.ptx.names);
    strings(&mut o, "PTX_PREFIX", &t.ptx.prefixes);
    strings(&mut o, "PTX_SUFFIX", &t.ptx.suffixes);
    Ok(o)
}

/// The two generated files of the table.
pub fn generate(text: &str) -> Result<Vec<(&'static str, String)>, String> {
    let t = parse(text)?;
    Ok(vec![(RUST_OUT, emit_rust(&t)?), (STAVE_OUT, emit_stave(&t)?)])
}
