//! The compiler-known items (`crates/stave-ir/tables/known.toml`): stave-ir's `Known` table
//! (`crates/stave-ir/src/generated/known_items.rs`, included by `known.rs`) and stage1's
//! (`stage1/ir/src/generated/known_items.stv`), so both compilers read one list of paths, panic
//! report entries, ABI signatures, and the items the release optimizer inlines. The params that
//! take a site row are written for stave-ir alone.

use std::fmt::Write;

use serde::Deserialize;

pub const TABLE: &str = "crates/stave-ir/tables/known.toml";
pub const RUST_OUT: &str = "crates/stave-ir/src/generated/known_items.rs";
pub const STAVE_OUT: &str = "stage1/ir/src/generated/known_items.stv";

/// The ABI types, in their Stave code order (`ITY_*`), with their Rust `ITy` variants.
pub const ITYS: [(&str, &str); 9] = [
    ("usize", "Usize"),
    ("isize", "Isize"),
    ("u32", "U32"),
    ("u64", "U64"),
    ("unit", "Unit"),
    ("u32x4", "U32x4"),
    ("mut_ptr_u8", "MutPtrU8"),
    ("const_ptr_u8", "ConstPtrU8"),
    ("const_ptr_usize", "ConstPtrUsize"),
];

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawTable {
    item: Vec<Item>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Item {
    pub variant: String,
    pub module: String,
    pub name: String,
    #[serde(default)]
    pub method: Option<String>,
    #[serde(default)]
    pub report: bool,
    #[serde(default)]
    pub params: Option<Vec<String>>,
    #[serde(default)]
    pub ret: Option<String>,
    #[serde(default)]
    pub inline: bool,
    #[serde(default)]
    pub site_param: Option<u8>,
}

impl Item {
    pub fn path(&self) -> String {
        match &self.method {
            Some(m) => format!("{}.{}.{m}", self.module, self.name),
            None => format!("{}.{}", self.module, self.name),
        }
    }
}

fn ity(name: &str) -> Result<usize, String> {
    ITYS.iter().position(|t| t.0 == name).ok_or_else(|| format!("{TABLE}: unknown ABI type `{name}`"))
}

/// Parses and checks the table: unique variants and paths, Rust-identifier variants, known ABI
/// types, `params` only with `ret`, `inline` on no item with `ret` or `report` (the optimizer
/// inlines only items that IR calls alone reach and that run on the caller's stack), `site_param`
/// a param index that, in an item with `ret`, names a `u32` param (the type of a site row).
pub fn parse(text: &str) -> Result<Vec<Item>, String> {
    let t: RawTable = toml::from_str(text).map_err(|e| format!("{TABLE}: {e}"))?;
    let mut seen_v = std::collections::BTreeSet::new();
    let mut seen_p = std::collections::BTreeSet::new();
    for it in &t.item {
        let v = &it.variant;
        if v.is_empty()
            || !v.chars().all(|c| c.is_ascii_alphanumeric())
            || !v.starts_with(|c: char| c.is_ascii_uppercase())
        {
            return Err(format!("{TABLE}: variant `{v}` is not a Rust variant name"));
        }
        if !seen_v.insert(v.clone()) {
            return Err(format!("{TABLE}: variant `{v}` twice"));
        }
        if !seen_p.insert(it.path()) {
            return Err(format!("{TABLE}: path `{}` twice", it.path()));
        }
        if it.params.is_some() && it.ret.is_none() {
            return Err(format!("{TABLE}: `{v}` has `params` without `ret`"));
        }
        if it.inline && (it.ret.is_some() || it.report) {
            return Err(format!("{TABLE}: `{v}` is `inline` but has `ret` or `report`"));
        }
        for p in it.params.iter().flatten() {
            ity(p)?;
        }
        if let Some(r) = &it.ret {
            ity(r)?;
        }
        if let Some(s) = it.site_param
            && it.ret.is_some()
            && it.params.iter().flatten().nth(usize::from(s)).is_none_or(|p| p != "u32")
        {
            return Err(format!("{TABLE}: `{v}` has `site_param = {s}`, which names no `u32` param"));
        }
    }
    Ok(t.item)
}

const HEADER: &str = "generated by tools/gen-tables from crates/stave-ir/tables/known.toml; do not edit";

pub fn emit_rust(items: &[Item]) -> Result<String, String> {
    let mut o = format!(
        "// {HEADER}\n// The compiler-known items, in `Known` order (`known.rs` includes this file).\n\nknown_items! {{\n"
    );
    for it in items {
        let _ = write!(o, "    {} = \"{}\" \"{}\"", it.variant, it.module, it.name);
        if let Some(m) = &it.method {
            let _ = write!(o, ".\"{m}\"");
        }
        o += ";\n";
    }
    o += "}\n\n// The panic report entries.\n";
    let reports: Vec<&Item> = items.iter().filter(|i| i.report).collect();
    let _ = writeln!(o, "const REPORTS: [Known; {}] = [", reports.len());
    for it in &reports {
        let _ = writeln!(o, "    Known::{},", it.variant);
    }
    o += "];\n\n// The items the release optimizer inlines like ordinary fns.\n";
    let inlined: Vec<&Item> = items.iter().filter(|i| i.inline).collect();
    let _ = writeln!(o, "const INLINED: [Known; {}] = [", inlined.len());
    for it in &inlined {
        let _ = writeln!(o, "    Known::{},", it.variant);
    }
    o += "];\n\n// The signature of an item the stages call with an argument list of their own.\n";
    o += "fn abi_table(k: Known) -> Option<(&'static [ITy], ITy)> {\n    match k {\n";
    for it in items {
        let Some(r) = &it.ret else { continue };
        let ps: Vec<String> = it
            .params
            .iter()
            .flatten()
            .map(|p| ity(p).map(|i| format!("ITy::{}", ITYS[i].1)))
            .collect::<Result<_, _>>()?;
        let _ = writeln!(
            o,
            "        Known::{} => Some((&[{}], ITy::{})),",
            it.variant,
            ps.join(", "),
            ITYS[ity(r)?].1
        );
    }
    o += "        _ => None,\n    }\n}\n";
    o += "\n// The param of an item that a site row is passed in.\n";
    o += "fn site_table(k: Known) -> Option<usize> {\n    match k {\n";
    for it in items {
        let Some(s) = it.site_param else { continue };
        let _ = writeln!(o, "        Known::{} => Some({s}),", it.variant);
    }
    o += "        _ => None,\n    }\n}\n";
    Ok(o)
}

fn pack(xs: &[String]) -> String {
    let (indent, width) = ("    ", 100);
    let mut out = String::new();
    let mut line = String::new();
    for it in xs {
        if !line.is_empty() && indent.len() + line.len() + it.len() + 2 > width {
            out += indent;
            out += line.trim_end();
            out.push('\n');
            line.clear();
        }
        line += it;
        line += ", ";
    }
    if !line.is_empty() {
        out += indent;
        out += line.trim_end();
        out.push('\n');
    }
    out
}

fn array(o: &mut String, name: &str, ty: &str, xs: &[String]) {
    let _ = writeln!(o, "pub const {name}: [{ty}; {}] = [", xs.len());
    *o += &pack(xs);
    *o += "];\n";
}

pub fn emit_stave(items: &[Item]) -> Result<String, String> {
    let mut o = format!("// {HEADER}\n");
    o += "// The compiler-known items by row, in stave-ir `Known` order. The path of item i (UTF-8) is\n";
    o += "// KNOWN_PATH[KNOWN_PATH_OFF[i]..KNOWN_PATH_OFF[i + 1]]; KNOWN_REPORT: a panic report entry;\n";
    o += "// KNOWN_INLINE: the release optimizer inlines it like an ordinary fn;\n";
    o += "// KNOWN_ABI_RET: the ABI result type (`ITY_NONE`: no ABI signature), its params\n";
    o += "// KNOWN_ABI_PARAM[KNOWN_ABI_OFF[i]..KNOWN_ABI_OFF[i + 1]].\n\n";
    let _ = writeln!(o, "pub const KNOWN_N: usize = {};", items.len());
    for (k, (name, _)) in ITYS.iter().enumerate() {
        let _ = writeln!(o, "pub const ITY_{}: u8 = {k};", name.to_ascii_uppercase());
    }
    o += "pub const ITY_NONE: u8 = 255;\n";
    o += "// ABI type i in messages (stave-ir `ITy`): ITY_NAME[ITY_NAME_OFF[i]..ITY_NAME_OFF[i + 1]].\n";
    let mut noff = vec!["0".to_string()];
    let mut nbytes = Vec::new();
    for (_, rust) in ITYS {
        nbytes.extend(rust.bytes().map(|b| b.to_string()));
        noff.push(nbytes.len().to_string());
    }
    array(&mut o, "ITY_NAME_OFF", "u32", &noff);
    array(&mut o, "ITY_NAME", "u8", &nbytes);
    o += "\n";
    let mut off = vec![0u32];
    let mut bytes = Vec::new();
    let mut aoff = vec![0u32];
    let mut params = Vec::new();
    let mut rets = Vec::new();
    for it in items {
        bytes.extend_from_slice(it.path().as_bytes());
        off.push(bytes.len() as u32);
        for p in it.params.iter().flatten() {
            params.push(ity(p)?.to_string());
        }
        aoff.push(params.len() as u32);
        rets.push(match &it.ret {
            Some(r) => ity(r)?.to_string(),
            None => "255".to_string(),
        });
    }
    let s = |v: &[u32]| v.iter().map(u32::to_string).collect::<Vec<_>>();
    array(&mut o, "KNOWN_PATH_OFF", "u32", &s(&off));
    array(&mut o, "KNOWN_PATH", "u8", &bytes.iter().map(u8::to_string).collect::<Vec<_>>());
    array(&mut o, "KNOWN_REPORT", "bool", &items.iter().map(|i| i.report.to_string()).collect::<Vec<_>>());
    array(&mut o, "KNOWN_INLINE", "bool", &items.iter().map(|i| i.inline.to_string()).collect::<Vec<_>>());
    array(&mut o, "KNOWN_ABI_RET", "u8", &rets);
    array(&mut o, "KNOWN_ABI_OFF", "u32", &s(&aoff));
    array(&mut o, "KNOWN_ABI_PARAM", "u8", &params);
    o += "// The parts of each path (`KNOWN_METHOD` empty for an item that is no method).\n";
    for (name, part) in [("KNOWN_MODULE", 0), ("KNOWN_NAME", 1), ("KNOWN_METHOD", 2)] {
        let mut poff = vec![0u32];
        let mut pbytes = Vec::new();
        for it in items {
            let text = match part {
                0 => it.module.as_str(),
                1 => it.name.as_str(),
                _ => it.method.as_deref().unwrap_or(""),
            };
            pbytes.extend(text.bytes().map(|b| b.to_string()));
            poff.push(pbytes.len() as u32);
        }
        array(&mut o, &format!("{name}_OFF"), "u32", &s(&poff));
        array(&mut o, name, "u8", &pbytes);
    }
    Ok(o)
}

/// The two generated files of the table.
pub fn generate(text: &str) -> Result<Vec<(&'static str, String)>, String> {
    let items = parse(text)?;
    Ok(vec![(RUST_OUT, emit_rust(&items)?), (STAVE_OUT, emit_stave(&items)?)])
}

#[cfg(test)]
mod tests {
    use super::*;

    const SMALL: &str = r#"
[[item]]
variant = "Trap"
module = "runtime.panic"
name = "trap"
report = true

[[item]]
variant = "SetUserSite"
module = "runtime.panic"
name = "set_user_site"
inline = true
"#;

    #[test]
    fn the_inline_column() {
        let items = parse(SMALL).unwrap();
        let rs = emit_rust(&items).unwrap();
        assert!(rs.contains("const INLINED: [Known; 1] = [\n    Known::SetUserSite,\n];\n"), "{rs}");
        let stv = emit_stave(&items).unwrap();
        assert!(stv.contains("pub const KNOWN_INLINE: [bool; 2] = [\n    false, true,\n];\n"), "{stv}");
        let bad = |from: &str, to: &str| parse(&SMALL.replacen(from, to, 1)).err().unwrap();
        assert!(bad("report = true", "report = true\ninline = true").contains("is `inline`"));
        assert!(bad("inline = true", "inline = true\nret = \"unit\"").contains("is `inline`"));
    }

    #[test]
    fn the_site_param_column() {
        let with = |keys: &str| parse(&SMALL.replacen("report = true", keys, 1));
        let rs = emit_rust(&with("site_param = 1").unwrap()).unwrap();
        let table = "fn site_table(k: Known) -> Option<usize> {\n    match k {\n";
        let arms = "        Known::Trap => Some(1),\n        _ => None,\n    }\n}\n";
        assert!(rs.contains(&format!("{table}{arms}")), "{rs}");
        // not a param index
        for v in ["-1", "256", "0.0", "true", "\"0\"", "[0]", "{ at = 0 }", "1979-05-27"] {
            let e = with(&format!("site_param = {v}")).err();
            assert!(e.as_ref().is_some_and(|e| e.contains("site_param")), "{v}: {e:?}");
        }
        assert!(with("site = 0").err().unwrap().contains("unknown field"));
        // against a signature: only a `u32` param
        let sig = |i: u8| format!("ret = \"unit\"\nparams = [\"usize\", \"u32\"]\nsite_param = {i}");
        assert!(with(&sig(1)).is_ok());
        for keys in [sig(0), sig(2), "ret = \"unit\"\nsite_param = 0".to_string()] {
            let e = with(&keys).err();
            assert!(e.as_ref().is_some_and(|e| e.contains("names no `u32` param")), "{keys}: {e:?}");
        }
    }
}
