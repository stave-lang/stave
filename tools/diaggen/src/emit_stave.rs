//! Emits `stage1/src/generated/diag_templates.stv`: the same table as stage0's, as Stave v0.4
//! top-level `const` items (parallel arrays plus `_FIRST` range tables).

use std::fmt::Write;

use crate::registry::{Applicability, Registry, Severity};

pub const HEADER: &str = "// generated by tools/diaggen from contracts/diagnostics.toml; do not edit\n";

const LAYOUT: &str = "\
//
// Diagnostic templates for stage1, the same table as stage0's
// crates/stave-diag/src/generated/templates.rs. Entries are sorted by code. A `_FIRST` table has
// one element more than the table it indexes: the items of row i are X[X_FIRST[i]] up to, not
// including, X[X_FIRST[i + 1]]. String tables hold no references (consts cannot, LANG.md §3): a
// string table X is `X: [u8; K]`, the UTF-8 bytes of all its strings concatenated, plus
// `X_OFF: [u32; N + 1]`; string j is the bytes X[X_OFF[j]] up to, not including, X[X_OFF[j + 1]].
// The comment above each string's bytes shows its spelling.
//   DIAG_*   one row per code. DIAG_SEVERITY: 0 error, 1 warning. A retired code has no holes
//            and no shapes (its severity is a placeholder).
//   HOLE_*   the declared holes of each code, by name. HOLE_KIND: 0 name, 1 path, 2 type,
//            3 token-kinds, 4 int, 5 place, 6 source, 7 text-literal. CHOICE_TEXT: the allowed
//            values of a text-literal hole.
//   SHAPE_*  the shapes of each code: the base (case \"\") first, then the cases by name, each
//            complete. SHAPE_HAS_FIX false: no fix (SHAPE_FIX is then \"\").
//            SHAPE_FIX_APPLICABILITY: 0 exact, 1 maybe, 2 placeholder (also without a fix).
//   LABEL_*  labels of each shape, in print order; LABEL_AT is \"primary\" or a role.
//   EDIT_*   fix edits of each shape.
// Templates: {hole} inserts a hole's value; {{ and }} are literal braces.
";

/// A string's spelling for a `//` comment: Rust debug quoting keeps it on one line.
fn spelling(s: &str) -> String {
    format!("{s:?}")
}

fn kind_id(kind: &str) -> u8 {
    match kind {
        "name" => 0,
        "path" => 1,
        "type" => 2,
        "token-kinds" => 3,
        "int" => 4,
        "place" => 5,
        "source" => 6,
        _ => 7,
    }
}

fn applicability_id(a: Applicability) -> u8 {
    match a {
        Applicability::Exact => 0,
        Applicability::Maybe => 1,
        Applicability::Placeholder => 2,
    }
}

/// Writes the lines `(code, comment)`, a comment after its code. The comments of consecutive
/// commented lines start in one column, one space after the longest code of the run: the layout
/// `stave fmt` gives.
fn commented(o: &mut String, lines: &[(String, String)]) {
    let mut k = 0;
    while k < lines.len() {
        let run = lines[k..].iter().take_while(|l| !l.1.is_empty()).count();
        if run == 0 {
            let _ = writeln!(o, "{}", lines[k].0);
            k += 1;
            continue;
        }
        let width = lines[k..k + run].iter().map(|l| l.0.chars().count()).max().unwrap_or(0);
        for (code, comment) in &lines[k..k + run] {
            let pad = width - code.chars().count();
            let _ = writeln!(o, "{code}{:pad$} // {comment}", "");
        }
        k += run;
    }
}

/// One `const` array: elements one per line, each with a trailing comment.
fn array(o: &mut String, name: &str, elem: &str, items: &[(String, String)]) {
    let _ = writeln!(o, "\nconst {name}: [{elem}; {}] = [", items.len());
    let lines: Vec<(String, String)> =
        items.iter().map(|(value, comment)| (format!("    {value},"), comment.clone())).collect();
    commented(o, &lines);
    o.push_str("];\n");
}

/// One string table: the byte pool `NAME: [u8; K]` and the offsets `NAME_OFF: [u32; N + 1]`.
fn strings(o: &mut String, name: &str, items: &[(String, String)]) {
    let total: usize = items.iter().map(|(v, _)| v.len()).sum();
    let mut offs = Vec::with_capacity(items.len() + 1);
    let mut at = 0usize;
    let _ = writeln!(o, "\nconst {name}: [u8; {total}] = [");
    for (j, (value, tag)) in items.iter().enumerate() {
        offs.push((at.to_string(), tag.clone()));
        if tag.is_empty() {
            let _ = writeln!(o, "    // {j}: {}", spelling(value));
        } else {
            let _ = writeln!(o, "    // {j} {tag}: {}", spelling(value));
        }
        for chunk in value.as_bytes().chunks(16) {
            let bytes: Vec<String> = chunk.iter().map(|b| b.to_string()).collect();
            let _ = writeln!(o, "    {},", bytes.join(", "));
        }
        at += value.len();
    }
    o.push_str("];\n");
    offs.push((at.to_string(), "end".to_string()));
    array(o, &format!("{name}_OFF"), "u32", &offs);
}

pub fn emit(reg: &Registry) -> String {
    let raw = |s: &str| s.to_string();
    let n = reg.entries.len();
    let mut code_text = Vec::with_capacity(n);
    let mut code_num = Vec::with_capacity(n);
    let mut severity = Vec::with_capacity(n);
    let mut retired = Vec::with_capacity(n);
    let mut located = Vec::with_capacity(n);
    let mut hole_first = Vec::with_capacity(n + 1);
    let mut shape_first = Vec::with_capacity(n + 1);
    let (mut hole_name, mut hole_kind, mut choice_first, mut choice_text) = (vec![], vec![], vec![], vec![]);
    let (mut shape_case, mut shape_message, mut shape_has_fix, mut shape_fix) =
        (vec![], vec![], vec![], vec![]);
    let mut shape_applicability = vec![];
    let (mut label_first, mut label_at, mut label_text) = (vec![], vec![], vec![]);
    let (mut edit_first, mut edit_at, mut edit_replacement) = (vec![], vec![], vec![]);
    let none = String::new;
    for e in &reg.entries {
        let c = e.code.clone();
        code_text.push((raw(&e.code), none()));
        code_num.push((e.number.to_string(), c.clone()));
        let sev = match e.severity {
            Severity::Error => "0",
            Severity::Warning => "1",
        };
        severity.push((sev.to_string(), c.clone()));
        retired.push((e.retired.to_string(), c.clone()));
        located.push((e.located.to_string(), c.clone()));
        hole_first.push((hole_name.len().to_string(), c.clone()));
        for h in &e.holes {
            let tag = format!("{c} {}", h.name);
            hole_name.push((raw(&h.name), c.clone()));
            hole_kind.push((kind_id(&h.kind).to_string(), tag.clone()));
            choice_first.push((choice_text.len().to_string(), tag.clone()));
            for ch in &h.choices {
                choice_text.push((raw(ch), tag.clone()));
            }
        }
        shape_first.push((shape_case.len().to_string(), c.clone()));
        for s in &e.shapes {
            let tag = if s.case.is_empty() { c.clone() } else { format!("{c} {}", s.case) };
            shape_case.push((raw(&s.case), c.clone()));
            shape_message.push((raw(&s.message), tag.clone()));
            shape_has_fix.push((s.fix.is_some().to_string(), tag.clone()));
            let desc = s.fix.as_ref().map(|f| f.description.as_str()).unwrap_or("");
            shape_fix.push((raw(desc), tag.clone()));
            let app = s.fix.as_ref().map_or(Applicability::Placeholder, |f| f.applicability);
            shape_applicability.push((applicability_id(app).to_string(), tag.clone()));
            label_first.push((label_at.len().to_string(), tag.clone()));
            for l in &s.labels {
                label_at.push((raw(&l.at), tag.clone()));
                label_text.push((raw(&l.text), tag.clone()));
            }
            edit_first.push((edit_at.len().to_string(), tag.clone()));
            for ed in s.fix.iter().flat_map(|f| &f.edits) {
                edit_at.push((raw(&ed.at), tag.clone()));
                edit_replacement.push((raw(&ed.replacement), tag.clone()));
            }
        }
    }
    hole_first.push((hole_name.len().to_string(), "end".to_string()));
    choice_first.push((choice_text.len().to_string(), "end".to_string()));
    shape_first.push((shape_case.len().to_string(), "end".to_string()));
    label_first.push((label_at.len().to_string(), "end".to_string()));
    edit_first.push((edit_at.len().to_string(), "end".to_string()));

    let mut o = String::new();
    o.push_str(HEADER);
    o.push_str(LAYOUT);
    let _ = writeln!(o, "\nconst DIAG_COUNT: usize = {n};");
    let _ = writeln!(o, "const HOLE_COUNT: usize = {};", hole_name.len());
    let _ = writeln!(o, "const CHOICE_COUNT: usize = {};", choice_text.len());
    let _ = writeln!(o, "const SHAPE_COUNT: usize = {};", shape_case.len());
    let _ = writeln!(o, "const LABEL_COUNT: usize = {};", label_at.len());
    let _ = writeln!(o, "const EDIT_COUNT: usize = {};", edit_at.len());
    strings(&mut o, "DIAG_CODE", &code_text);
    array(&mut o, "DIAG_NUMBER", "u16", &code_num);
    array(&mut o, "DIAG_SEVERITY", "u8", &severity);
    array(&mut o, "DIAG_RETIRED", "bool", &retired);
    array(&mut o, "DIAG_LOCATED", "bool", &located);
    array(&mut o, "DIAG_HOLE_FIRST", "u32", &hole_first);
    array(&mut o, "DIAG_SHAPE_FIRST", "u32", &shape_first);
    strings(&mut o, "HOLE_NAME", &hole_name);
    array(&mut o, "HOLE_KIND", "u8", &hole_kind);
    array(&mut o, "HOLE_CHOICE_FIRST", "u32", &choice_first);
    strings(&mut o, "CHOICE_TEXT", &choice_text);
    strings(&mut o, "SHAPE_CASE", &shape_case);
    strings(&mut o, "SHAPE_MESSAGE", &shape_message);
    array(&mut o, "SHAPE_HAS_FIX", "bool", &shape_has_fix);
    strings(&mut o, "SHAPE_FIX", &shape_fix);
    array(&mut o, "SHAPE_FIX_APPLICABILITY", "u8", &shape_applicability);
    array(&mut o, "SHAPE_LABEL_FIRST", "u32", &label_first);
    strings(&mut o, "LABEL_AT", &label_at);
    strings(&mut o, "LABEL_TEXT", &label_text);
    array(&mut o, "SHAPE_EDIT_FIRST", "u32", &edit_first);
    strings(&mut o, "EDIT_AT", &edit_at);
    strings(&mut o, "EDIT_REPLACEMENT", &edit_replacement);
    o
}
