//! Emits `crates/stave-diag/src/generated/templates.rs`.

use std::fmt::Write;

use crate::registry::{Registry, Severity};

pub const HEADER: &str = "// generated by tools/diaggen from contracts/diagnostics.toml; do not edit\n";

fn lit(s: &str) -> String {
    format!("{s:?}")
}

fn kind_variant(kind: &str) -> &'static str {
    match kind {
        "name" => "Name",
        "path" => "Path",
        "type" => "Type",
        "token-kinds" => "TokenKinds",
        "int" => "Int",
        "place" => "Place",
        "source" => "Source",
        // The registry check admits only the eight kinds.
        _ => "TextLiteral",
    }
}

pub fn emit(reg: &Registry) -> String {
    let mut o = String::new();
    o.push_str(HEADER);
    o.push_str(
        "// Registry entries sorted by code; shapes: the base (case \"\") first, then the cases by name,\n",
    );
    o.push_str(
        "// each complete. A retired entry has no holes or shapes (its severity is a placeholder).\n\n",
    );
    o.push_str("#![allow(unused_imports)]\n\n");
    o.push_str("use super::{EditTemplate, Entry, FixTemplate, Hole, HoleKind, LabelTemplate, Shape};\n");
    o.push_str("use crate::diagnostic::Severity;\n\n");
    o.push_str("pub(super) static ENTRIES: &[Entry] = &[\n");
    for e in &reg.entries {
        let sev = match e.severity {
            Severity::Error => "Error",
            Severity::Warning => "Warning",
        };
        let _ = writeln!(o, "    Entry {{");
        let _ = writeln!(o, "        code: {},", lit(&e.code));
        let _ = writeln!(o, "        severity: Severity::{sev},");
        let _ = writeln!(o, "        area: {},", lit(&e.area));
        let _ = writeln!(o, "        rule: {},", lit(&e.rule));
        let _ = writeln!(o, "        retired: {},", e.retired);
        let _ = writeln!(o, "        located: {},", e.located);
        if e.holes.is_empty() {
            o.push_str("        holes: &[],\n");
        } else {
            o.push_str("        holes: &[\n");
            for h in &e.holes {
                let choices: Vec<String> = h.choices.iter().map(|c| lit(c)).collect();
                let _ = writeln!(
                    o,
                    "            Hole {{ name: {}, kind: HoleKind::{}, choices: &[{}] }},",
                    lit(&h.name),
                    kind_variant(&h.kind),
                    choices.join(", ")
                );
            }
            o.push_str("        ],\n");
        }
        if e.shapes.is_empty() {
            o.push_str("        shapes: &[],\n");
        } else {
            o.push_str("        shapes: &[\n");
            for s in &e.shapes {
                o.push_str("            Shape {\n");
                let _ = writeln!(o, "                case: {},", lit(&s.case));
                let _ = writeln!(o, "                message: {},", lit(&s.message));
                if s.labels.is_empty() {
                    o.push_str("                labels: &[],\n");
                } else {
                    o.push_str("                labels: &[\n");
                    for l in &s.labels {
                        let _ = writeln!(
                            o,
                            "                    LabelTemplate {{ at: {}, text: {} }},",
                            lit(&l.at),
                            lit(&l.text)
                        );
                    }
                    o.push_str("                ],\n");
                }
                match &s.fix {
                    None => o.push_str("                fix: None,\n"),
                    Some(f) => {
                        o.push_str("                fix: Some(FixTemplate {\n");
                        let _ = writeln!(o, "                    description: {},", lit(&f.description));
                        if f.edits.is_empty() {
                            o.push_str("                    edits: &[],\n");
                        } else {
                            o.push_str("                    edits: &[\n");
                            for ed in &f.edits {
                                let _ = writeln!(
                                    o,
                                    "                        EditTemplate {{ at: {}, replacement: {} }},",
                                    lit(&ed.at),
                                    lit(&ed.replacement)
                                );
                            }
                            o.push_str("                    ],\n");
                        }
                        o.push_str("                }),\n");
                    }
                }
                o.push_str("            },\n");
            }
            o.push_str("        ],\n");
        }
        o.push_str("    },\n");
    }
    o.push_str("];\n");
    o
}
