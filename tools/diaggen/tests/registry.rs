//! Checks of contracts/diagnostics.toml (format in its header) and its cross-check against
//! the human tables.

use diaggen::registry::HOLE_KINDS;
use diaggen::template::{Segment, parse};
use diaggen::{RUST_OUT, STAVE_OUT, check, find_root, generate, load, md};

fn root() -> std::path::PathBuf {
    find_root().expect("repository root")
}

#[test]
fn real_registry_passes() {
    let reg = load(&root()).unwrap_or_else(|e| panic!("{e}"));
    assert_eq!(reg.entries.len(), 148, "130 rows of diagnostic-codes.md + 12 E11xx + 6 E12xx");
    for e in &reg.entries {
        assert!(md::is_code(&e.code), "{}", e.code);
        for h in &e.holes {
            assert!(HOLE_KINDS.contains(&h.kind.as_str()));
            assert_eq!(h.kind == "text-literal", !h.choices.is_empty(), "{} {}", e.code, h.name);
        }
        if !e.retired {
            let base = &e.shapes[0];
            assert!(base.case.is_empty() && !base.message.is_empty());
            if e.severity == diaggen::registry::Severity::Error {
                assert!(e.shapes.iter().all(|s| s.fix.is_some()), "{}", e.code);
            }
        }
    }
    let codes: Vec<&str> = reg.entries.iter().map(|e| e.code.as_str()).collect();
    let mut sorted = codes.clone();
    sorted.sort();
    sorted.dedup();
    assert_eq!(codes, sorted, "unique and sorted");
}

#[test]
fn every_table_code_has_an_entry() {
    let r = root();
    let reg = load(&r).unwrap_or_else(|e| panic!("{e}"));
    for t in diaggen::TABLES {
        let text = std::fs::read_to_string(r.join(t)).expect("table");
        let rows = md::rows(t, &text);
        assert!(!rows.is_empty(), "{t} has code rows");
        for row in rows {
            assert!(reg.entries.iter().any(|e| e.code == row.code), "{} of {t}", row.code);
        }
    }
}

#[test]
fn generated_files_are_current_and_deterministic() {
    let r = root();
    let reg = load(&r).unwrap_or_else(|e| panic!("{e}"));
    let a = generate(&reg);
    let b = generate(&load(&r).unwrap_or_else(|e| panic!("{e}")));
    assert_eq!(a, b);
    for (rel, content) in &a {
        let on_disk = std::fs::read_to_string(r.join(rel)).unwrap_or_default();
        assert!(on_disk == *content, "{rel} is stale: run `tools/ci-step/run.sh gen`");
        assert!(
            content
                .starts_with("// generated by tools/diaggen from contracts/diagnostics.toml; do not edit\n")
        );
    }
    assert_eq!(a[0].0, RUST_OUT);
    assert_eq!(a[1].0, STAVE_OUT);
}

#[test]
fn stave_table_is_const_items_only() {
    let reg = load(&root()).unwrap_or_else(|e| panic!("{e}"));
    let stave = &generate(&reg)[1].1;
    let mut in_array = false;
    for line in stave.lines() {
        let t = line.trim();
        if t.is_empty() || t.starts_with("//") {
            continue;
        }
        if in_array {
            if t == "];" {
                in_array = false;
            } else {
                // Elements: integer or bool literals only, then an optional comment.
                let code = t.split("//").next().unwrap_or("");
                assert!(
                    code.split(',').map(str::trim).all(|x| x.is_empty()
                        || x == "true"
                        || x == "false"
                        || x.bytes().all(|b| b.is_ascii_digit())),
                    "not a literal element: {line}"
                );
            }
            continue;
        }
        assert!(!t.contains('"') && !t.contains("&str"), "no strings or references in consts: {line}");
        assert!(t.starts_with("const ") && t.contains(": ") && t.contains(" = "), "not a const item: {line}");
        in_array = t.ends_with('[');
        assert!(in_array || t.ends_with(';'), "{line}");
        assert!(!t.contains('\t'));
    }
    assert!(!in_array, "unterminated array");
}

// ---------- fixtures ----------

const MD: &str = "\
| Code | Rule |
|---|---|
| E0001 | first |
| E0002 | second |
";

fn entry(code: &str, body: &str) -> String {
    format!("[[diag]]\ncode = \"{code}\"\n{body}\n")
}

const OK1: &str = "severity = \"error\"\narea = \"lex-parse\"\nrule = \"first\"\n\
                   message = \"m\"\nfix = { description = \"do it\" }";
const OK2: &str = "severity = \"warning\"\narea = \"lex-parse\"\nrule = \"second\"\nmessage = \"w\"";

fn run(toml: &str) -> Result<(), String> {
    check(toml, &[("codes.md", MD)]).map(|_| ()).map_err(|e| e.to_string())
}

fn fails_with(toml: &str, needle: &str) {
    match run(toml) {
        Ok(()) => panic!("accepted, expected {needle:?}:\n{toml}"),
        Err(e) => assert!(e.contains(needle), "expected {needle:?}, got:\n{e}"),
    }
}

fn two(second: &str) -> String {
    entry("E0001", OK1) + &entry("E0002", second)
}

#[test]
fn fixture_baseline_passes() {
    run(&two(OK2)).unwrap_or_else(|e| panic!("{e}"));
}

#[test]
fn code_format_uniqueness_and_order() {
    fails_with(&(entry("E001", OK1) + &entry("E0002", OK2)), "does not match ^E[0-9]{4}$");
    fails_with(&(entry("E0001", OK1) + &entry("E0001", OK1) + &entry("E0002", OK2)), "appears twice");
    fails_with(&(entry("E0002", OK2) + &entry("E0001", OK1)), "not sorted");
}

#[test]
fn table_and_registry_list_the_same_codes() {
    fails_with(&entry("E0001", OK1), "E0002: row in codes.md has no entry");
    let extra = two(OK2) + &entry("E0003", &OK2.replace("second", "third"));
    fails_with(&extra, "E0003: has an entry in diagnostics.toml but no row");
    let dup = check(&two(OK2), &[("a.md", MD), ("b.md", MD)]).map_err(|e| e.to_string());
    assert!(dup.is_err_and(|e| e.contains("listed twice")));
}

#[test]
fn errors_need_message_and_fix() {
    fails_with(
        &two(&OK1
            .replace("rule = \"first\"", "rule = \"second\"")
            .replace("fix = { description = \"do it\" }", "")),
        "has no `fix`",
    );
    fails_with(
        &two("severity = \"error\"\narea = \"lex-parse\"\nrule = \"r\"\nfix = { description = \"d\" }"),
        "`message` missing",
    );
    fails_with(&two(&OK2.replace("warning", "fatal")), "is not \"error\" or \"warning\"");
    fails_with(&two(&OK2.replace("lex-parse", "types")), "the code's range is \"lex-parse\"");
    fails_with(&two(&OK2.replace("message = \"w\"", "message = \"w.\"")), "ends with a period");
}

#[test]
fn fix_applicability() {
    use diaggen::registry::Applicability::{Exact, Maybe, Placeholder};
    let edits = "edits = [{ at = \"primary\", replacement = \"x\" }]";
    let with = |fix: &str| two(&format!("{OK2}\nfix = {{ description = \"d\", {fix} }}"));
    let of = |toml: &str| {
        let reg = check(toml, &[("codes.md", MD)]).unwrap_or_else(|e| panic!("{e}"));
        reg.entries[1].shapes.iter().map(|s| s.fix.as_ref().map(|f| f.applicability)).collect::<Vec<_>>()
    };
    // defaults: `placeholder` without edits, `maybe` with edits
    assert_eq!(of(&two(&format!("{OK2}\nfix = {{ description = \"d\" }}"))), [Some(Placeholder)]);
    assert_eq!(of(&with(edits)), [Some(Maybe)]);
    assert_eq!(of(&with(&format!("applicability = \"exact\", {edits}"))), [Some(Exact)]);
    assert_eq!(of(&with(&format!("applicability = \"placeholder\", {edits}"))), [Some(Placeholder)]);
    assert_eq!(of(&with("applicability = \"placeholder\"")), [Some(Placeholder)]);
    // a case's fix replaces the entry's whole fix, applicability included
    let case = format!(
        "{}\n[diag.cases.c]\nfix = {{ description = \"e\", {edits} }}",
        with(&format!("applicability = \"exact\", {edits}"))
    );
    assert_eq!(of(&case), [Some(Exact), Some(Maybe)]);
    fails_with(&with(&format!("applicability = \"sure\", {edits}")), "applicability \"sure\" is not");
    fails_with(&with("applicability = \"exact\""), "on a fix without edits");
    fails_with(&with("applicability = \"maybe\""), "on a fix without edits");
    let bad_case = format!(
        "{}\n[diag.cases.c]\nfix = {{ description = \"e\", applicability = \"exact\" }}",
        with(edits)
    );
    fails_with(&bad_case, "case c: fix: applicability \"exact\" on a fix without edits");
}

#[test]
fn exact_fixes_of_the_registry() {
    use diaggen::registry::Applicability;
    let reg = load(&root()).unwrap_or_else(|e| panic!("{e}"));
    let mut exact = Vec::new();
    for e in &reg.entries {
        for s in &e.shapes {
            let Some(f) = &s.fix else { continue };
            assert!(
                !f.edits.is_empty() || f.applicability == Applicability::Placeholder,
                "{} {:?}: a fix without edits is a placeholder",
                e.code,
                s.case
            );
            if f.applicability == Applicability::Exact {
                exact.push((e.code.as_str(), s.case.as_str()));
            }
        }
    }
    assert_eq!(
        exact,
        [
            ("E0017", ""),
            ("E0023", ""),
            ("E0024", "ref"),
            ("E0026", "unit"),
            ("E0027", "ret"),
            ("E0210", ""),
            ("E0907", ""),
        ],
        "an exact fix is applied unreviewed by `stave fix`: extend this list on purpose"
    );
}

#[test]
fn hole_kinds_and_choices() {
    fails_with(
        &two(&format!("{OK2}\nholes = {{ a = \"colour\" }}").replace("\"w\"", "\"w {a}\"")),
        "unknown kind",
    );
    fails_with(
        &two(&format!("{OK2}\nholes = {{ a = \"text-literal\" }}").replace("\"w\"", "\"w {a}\"")),
        "has no `choices`",
    );
    fails_with(
        &two(&format!("{OK2}\nholes = {{ a = \"name\" }}\nchoices = {{ a = [\"x\"] }}")
            .replace("\"w\"", "\"w {a}\"")),
        "only text-literal",
    );
    let good = format!("{OK2}\nholes = {{ a = \"text-literal\" }}\nchoices = {{ a = [\"x\", \"y\"] }}")
        .replace("\"w\"", "\"w {a}\"");
    run(&two(&good)).unwrap_or_else(|e| panic!("{e}"));
    for kind in HOLE_KINDS.iter().filter(|k| **k != "text-literal") {
        let t = format!("{OK2}\nholes = {{ a = \"{kind}\" }}").replace("\"w\"", "\"w {a}\"");
        run(&two(&t)).unwrap_or_else(|e| panic!("{kind}: {e}"));
    }
}

#[test]
fn undeclared_and_unused_holes() {
    fails_with(&two(&OK2.replace("\"w\"", "\"w {b}\"")), "hole {b} is not declared");
    fails_with(
        &two(&format!("{OK2}\nholes = {{ a = \"int\" }}")),
        "hole a is declared but used by no template",
    );
    // A hole used only by a case counts as used.
    let case = format!("{OK2}\nholes = {{ a = \"int\" }}\n\n[diag.cases.other]\nmessage = \"w {{a}}\"");
    run(&two(&case)).unwrap_or_else(|e| panic!("{e}"));
    fails_with(
        &two(&format!("{OK2}\n\n[diag.cases.other]\nmessage = \"w {{zz}}\"")),
        "case other: message: hole {zz} is not declared",
    );
    // Labels at "primary" are not allowed for a location-less entry.
    let noloc = format!("{OK2}\nlocated = false\nlabels = [{{ at = \"primary\", text = \"t\" }}]");
    fails_with(&two(&noloc), "location-less");
}

#[test]
fn brace_escapes() {
    assert_eq!(
        parse("a {{b}} {c}").expect("ok"),
        [Segment::Text("a {b} ".into()), Segment::Hole("c".into())]
    );
    assert_eq!(
        parse("`{{{x}}}`").expect("ok"),
        [Segment::Text("`{".into()), Segment::Hole("x".into()), Segment::Text("}`".into())]
    );
    assert!(parse("a { b").is_err());
    assert!(parse("a } b").is_err());
    assert!(parse("{}").is_err());
    assert!(parse("{Bad}").is_err());
    // In the registry: escaped braces are not holes.
    run(&two(&OK2.replace("\"w\"", "\"w `.{{` }}\""))).unwrap_or_else(|e| panic!("{e}"));
    fails_with(&two(&OK2.replace("\"w\"", "\"w {\"")), "unclosed");
}

#[test]
fn retired_codes_stay_listed() {
    let md = MD.replace("| second |", "| retired (was: second) |");
    let retired = "rule = \"second\"\nretired = true";
    check(&two(retired), &[("codes.md", &md)]).unwrap_or_else(|e| panic!("{e}"));
    // Retired in the table, absent or active in the registry: both fail.
    let missing = check(&entry("E0001", OK1), &[("codes.md", &md)]).map_err(|e| e.to_string());
    assert!(missing.is_err_and(|e| e.contains("E0002: row in codes.md has no entry")));
    let active = check(&two(OK2), &[("codes.md", &md)]).map_err(|e| e.to_string());
    assert!(active.is_err_and(|e| e.contains("retired is false")));
    // A retired entry holds only code, rule, retired.
    fails_with(&two(&format!("{retired}\nmessage = \"m\"")), "retired entry has `message`");
}

