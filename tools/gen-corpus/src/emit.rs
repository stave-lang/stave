//! Phase 2: module and package text.

use crate::body::{Body, Ctx, How, RetCtx, Vis};
use crate::mix::Mix;
use crate::model::*;
use crate::names::{NOTES, push_pascal};
use crate::rng::Rng;
use std::fmt::Write;

fn ret_ctx(r: Ret) -> RetCtx {
    match r {
        Ret::Unit => RetCtx::Unit,
        Ret::Sc(t) => RetCtx::Sc(t),
        Ret::S(s) => RetCtx::S(s),
        Ret::E(e) => RetCtx::E(e),
        Ret::Opt(t) => RetCtx::Opt(t),
        Ret::Res(t, e) => RetCtx::Res(t, e),
        Ret::Tup(a, b) => RetCtx::Tup(a, b),
        Ret::RefSc(_) | Ret::RefS(_) | Ret::MutSc(_) | Ret::T | Ret::RefT | Ret::Cell(_) => RetCtx::Fixed,
    }
}

struct Emitter<'c, 'a> {
    cx: &'c Ctx<'a>,
    p: &'a ModPlan,
    out: String,
    r: Rng,
    vis: Vis,
}

/// Generates the text of module `me`.
pub fn module_text(plans: &[ModPlan], me: u32, mix: &Mix, seed: u64) -> String {
    let cx = Ctx::new(plans, me, mix);
    let p = &plans[me as usize];
    let mut em = Emitter {
        cx: &cx,
        p,
        out: String::with_capacity(p.budget as usize * 48),
        r: Rng::derive(seed, u64::from(me), 4),
        vis: Vis::default(),
    };
    em.module();
    em.out
}

impl<'a> Emitter<'_, 'a> {
    fn body<'s>(&'s mut self, rank: u8, ret: RetCtx) -> Body<'s, 'a> {
        Body::new(self.cx, &mut self.out, &mut self.r, self.vis, rank, ret)
    }

    fn module(&mut self) {
        let p = self.p;
        let plans = self.cx.plans;
        let _ = writeln!(self.out, "// module {} (generated by gen-corpus)", p.dotted());
        if p.uses_io {
            self.out.push_str("import std.io;\n");
        }
        for &m in &p.imports {
            let _ = writeln!(self.out, "import {} as m{m};", plans[m as usize].dotted());
        }
        for &it in &p.items {
            self.out.push('\n');
            match it {
                Item::Fn(i) => {
                    self.func(&p.fns[i as usize]);
                    self.vis.fns = i + 1;
                }
                Item::Struct(i) => {
                    self.struct_item(&p.structs[i as usize]);
                    self.vis.structs = i + 1;
                }
                Item::Enum(i) => {
                    self.enum_item(&p.enums[i as usize]);
                    self.vis.enums = i + 1;
                }
                Item::Impl(i) => {
                    self.impl_item(&p.impls[i as usize]);
                    self.vis.impls = i + 1;
                }
                Item::Trait(i) => self.trait_item(&p.traits[i as usize]),
                Item::TraitImpl(i) => {
                    self.timpl_item(&p.timpls[i as usize]);
                    self.vis.timpls = i + 1;
                }
                Item::Const(i) => {
                    self.const_item(&p.consts[i as usize]);
                    self.vis.consts = i + 1;
                }
                Item::Alias(i) => {
                    let a = &p.aliases[i as usize];
                    let _ = writeln!(self.out, "pub type {} = {};", a.name, a.ty.name());
                }
            }
        }
        for i in 0..p.filler {
            let v = self.r.below(1000);
            let _ = writeln!(self.out, "pub const PAD_{i}: u32 = {v};");
        }
    }

    fn ptype(&mut self, t: PTy) {
        let s = &self.p.structs;
        let e = &self.p.enums;
        match t {
            PTy::Sc(x) => self.out.push_str(x.name()),
            PTy::Ref(i) => {
                self.out.push('&');
                self.out.push_str(&s[i as usize].name);
            }
            PTy::Mut(i) => {
                self.out.push_str("&mut ");
                self.out.push_str(&s[i as usize].name);
            }
            PTy::Val(i) => self.out.push_str(&s[i as usize].name),
            PTy::EVal(i) => self.out.push_str(&e[i as usize].name),
            PTy::T => self.out.push('T'),
            PTy::RefT => self.out.push_str("&T"),
        }
    }

    fn rtype(&mut self, r: Ret) {
        let p = self.p;
        let o = &mut self.out;
        match r {
            Ret::Unit => {}
            Ret::Sc(t) => {
                let _ = write!(o, " -> {}", t.name());
            }
            Ret::S(s) => {
                let _ = write!(o, " -> {}", p.structs[s as usize].name);
            }
            Ret::E(e) => {
                let _ = write!(o, " -> {}", p.enums[e as usize].name);
            }
            Ret::Opt(t) => {
                let _ = write!(o, " -> Option<{}>", t.name());
            }
            Ret::Res(t, e) => {
                let _ = write!(o, " -> Result<{}, {}>", t.name(), p.enums[e as usize].name);
            }
            Ret::Tup(a, b) => {
                let _ = write!(o, " -> ({}, {})", a.name(), b.name());
            }
            Ret::RefSc(t) => {
                let _ = write!(o, " -> &{} from p0", t.name());
            }
            Ret::RefS(s) => {
                let _ = write!(o, " -> &{} from p0 + p1", p.structs[s as usize].name);
            }
            Ret::MutSc(t) => {
                let _ = write!(o, " -> &mut {} from p0", t.name());
            }
            Ret::T => o.push_str(" -> T"),
            Ret::RefT => o.push_str(" -> &T from p0 + p1"),
            Ret::Cell(g) => {
                let _ = write!(o, " -> {}<T>", p.structs[g as usize].name);
            }
        }
    }

    fn func(&mut self, f: &'a FnDef) {
        if f.doc {
            self.out.push_str("//");
            for _ in 0..self.r.range(3, 7) {
                let w = NOTES[self.r.below(NOTES.len() as u32) as usize];
                self.out.push(' ');
                self.out.push_str(w);
            }
            self.out.push('\n');
        }
        if f.public {
            self.out.push_str("pub ");
        }
        self.out.push_str("fn ");
        self.out.push_str(&f.name);
        match f.kind {
            FnKind::Pick | FnKind::RefPick | FnKind::GenCtor(_) => self.out.push_str("<T>"),
            FnKind::Bound(tr) => {
                let _ = write!(self.out, "<T: {}>", self.p.traits[tr as usize].name);
            }
            FnKind::Const => self.out.push_str("<const N: u32>"),
            FnKind::Plain => {}
        }
        self.out.push('(');
        for (i, &t) in f.params.iter().enumerate() {
            if i > 0 {
                self.out.push_str(", ");
            }
            let _ = write!(self.out, "p{i}: ");
            self.ptype(t);
        }
        self.out.push(')');
        self.rtype(f.ret);
        self.out.push_str(" {\n");
        let rc = ret_ctx(f.ret);
        let p = self.p;
        let mut b = self.body(f.rank, rc);
        for (i, &t) in f.params.iter().enumerate() {
            b.param(i, t);
        }
        match (f.kind, f.ret) {
            (FnKind::Plain, Ret::Unit) => b.block(f.body, 1),
            (FnKind::Plain, Ret::RefSc(t)) => {
                b.block(f.body - 1, 1);
                let s = match f.params[0] {
                    PTy::Ref(s) => s,
                    _ => 0,
                };
                let names: Vec<&str> = p.structs[s as usize]
                    .fields
                    .iter()
                    .filter(|x| x.ty == FTy::Sc(t))
                    .map(|x| x.name)
                    .collect();
                b.indent(1);
                if names.len() >= 2 {
                    b.push("return if ");
                    b.cond();
                    b.push(" then &p0.");
                    b.push(names[0]);
                    b.push(" else &p0.");
                    b.push(names[names.len() - 1]);
                    b.push(";\n");
                } else {
                    b.push("return &p0.");
                    b.push(names.first().copied().unwrap_or("x"));
                    b.push(";\n");
                }
            }
            (FnKind::Plain, Ret::RefS(_)) => {
                b.block(f.body - 1, 1);
                b.indent(1);
                b.push("return if ");
                b.cond();
                b.push(" then p0 else p1;\n");
            }
            (FnKind::Plain, Ret::MutSc(t)) => {
                b.block(f.body - 1, 1);
                let s = match f.params[0] {
                    PTy::Mut(s) => s,
                    _ => 0,
                };
                let name =
                    p.structs[s as usize].fields.iter().find(|x| x.ty == FTy::Sc(t)).map_or("x", |x| x.name);
                b.indent(1);
                b.push("return &mut p0.");
                b.push(name);
                b.push(";\n");
            }
            (FnKind::Plain, _) => {
                b.block(f.body - 1, 1);
                b.final_return(1);
            }
            (FnKind::Pick, _) => {
                b.block(f.body - 1, 1);
                b.push("    return if p0 then p1 else p2;\n");
            }
            (FnKind::RefPick, _) => {
                b.block(f.body - 1, 1);
                b.push("    return if p2 then p0 else p1;\n");
            }
            (FnKind::Bound(tr), _) => {
                b.block(f.body - 1, 1);
                let m0 = &p.traits[tr as usize].methods[0];
                b.push("    return p0.");
                b.push(&m0.name);
                if m0.arg.is_some() {
                    b.push("(p1);\n");
                } else if m0.ret.is_int() {
                    b.push("() +% p1;\n");
                } else {
                    b.push("() + p1;\n");
                }
            }
            (FnKind::Const, _) => {
                b.block(f.body - 1, 1);
                b.push("    return p0 *% N;\n");
            }
            (FnKind::GenCtor(gs), _) => {
                b.block(f.body - 1, 1);
                b.push("    return ");
                b.gen_lit(gs);
                b.push(";\n");
            }
        }
        self.out.push_str("}\n");
    }

    fn fty(&mut self, t: FTy) {
        match t {
            FTy::Sc(x) => self.out.push_str(x.name()),
            FTy::S(i) => self.out.push_str(&self.p.structs[i as usize].name),
            FTy::T => self.out.push('T'),
        }
    }

    fn struct_item(&mut self, s: &'a StructDef) {
        let _ = write!(self.out, "pub struct {}{} {{", s.name, if s.generic { "<T>" } else { "" });
        if s.fields.is_empty() {
            self.out.push_str("}\n");
            return;
        }
        self.out.push('\n');
        for f in &s.fields {
            let _ = write!(self.out, "    pub {}: ", f.name);
            self.fty(f.ty);
            self.out.push_str(",\n");
        }
        self.out.push_str("}\n");
    }

    fn enum_item(&mut self, e: &'a EnumDef) {
        let _ = writeln!(self.out, "pub enum {} {{", e.name);
        for v in &e.variants {
            self.out.push_str("    ");
            push_pascal(&mut self.out, v.name);
            match &v.kind {
                VKind::Unit => {}
                VKind::Tup(ts) => {
                    self.out.push('(');
                    for (i, t) in ts.iter().enumerate() {
                        if i > 0 {
                            self.out.push_str(", ");
                        }
                        self.out.push_str(t.name());
                    }
                    self.out.push(')');
                }
                VKind::Rec(fs) => {
                    self.out.push_str(" { ");
                    for (i, (n, t)) in fs.iter().enumerate() {
                        if i > 0 {
                            self.out.push_str(", ");
                        }
                        let _ = write!(self.out, "{n}: {}", t.name());
                    }
                    self.out.push_str(" }");
                }
            }
            self.out.push_str(",\n");
        }
        self.out.push_str("}\n");
    }

    fn impl_item(&mut self, imp: &'a ImplDef) {
        let s = &self.p.structs[imp.target as usize];
        if s.generic {
            let _ = writeln!(self.out, "impl<T> {}<T> {{", s.name);
        } else {
            let _ = writeln!(self.out, "impl {} {{", s.name);
        }
        for m in &imp.methods {
            self.method(imp.target, s, m);
        }
        self.out.push_str("}\n");
    }

    fn method(&mut self, st: u32, s: &'a StructDef, m: &'a Method) {
        let fname = |fi: u32| s.fields[fi as usize].name;
        let fsc = |fi: u32| match s.fields[fi as usize].ty {
            FTy::Sc(t) => t,
            _ => Sc::U32,
        };
        let _ = write!(self.out, "    pub fn {}(", m.name);
        let (recv, ret): (Option<How>, RetCtx) = match m.kind {
            MKind::Ctor => {
                let mut first = true;
                let mut i = 0;
                for f in &s.fields {
                    if let FTy::Sc(t) = f.ty {
                        if !first {
                            self.out.push_str(", ");
                        }
                        first = false;
                        let _ = write!(self.out, "p{i}: {}", t.name());
                        i += 1;
                    }
                }
                self.out.push_str(") -> Self {\n");
                (None, RetCtx::Fixed)
            }
            MKind::Get(fi) => {
                let _ = writeln!(self.out, "&self) -> {} {{", fsc(fi).name());
                (Some(How::SelfRef), RetCtx::Sc(fsc(fi)))
            }
            MKind::Bump(fi) => {
                let _ = writeln!(self.out, "&mut self, p0: {}) {{", fsc(fi).name());
                (Some(How::SelfMut), RetCtx::Fixed)
            }
            MKind::Consume(fi) => {
                let _ = writeln!(self.out, "self) -> {} {{", fsc(fi).name());
                (Some(How::SelfVal), RetCtx::Sc(fsc(fi)))
            }
            MKind::RefGet(fi) => {
                let _ = writeln!(self.out, "&self) -> &{} from self {{", fsc(fi).name());
                (Some(How::SelfRef), RetCtx::Fixed)
            }
            MKind::Mix(fi) => {
                let _ = writeln!(self.out, "&self, p0: &Self) -> {} {{", fsc(fi).name());
                (Some(How::SelfRef), RetCtx::Fixed)
            }
            MKind::GGet => {
                self.out.push_str("&self) -> &T from self {\n");
                (Some(How::SelfRef), RetCtx::Fixed)
            }
            MKind::GPut => {
                self.out.push_str("&mut self, p0: T) {\n");
                (Some(How::SelfMut), RetCtx::Fixed)
            }
            MKind::GCount => {
                self.out.push_str("&self) -> u32 {\n");
                (Some(How::SelfRef), RetCtx::Sc(Sc::U32))
            }
        };
        let mut b = self.body(m.rank, ret);
        if let Some(h) = recv {
            b.self_param(st, h);
        }
        match m.kind {
            MKind::Ctor => {
                let mut i = 0;
                for f in &s.fields {
                    if let FTy::Sc(t) = f.ty {
                        b.param(i, PTy::Sc(t));
                        i += 1;
                    }
                }
                b.block(m.body - 1, 2);
                b.push("        return ");
                b.ctor_lit(st);
                b.push(";\n");
            }
            MKind::Get(_) | MKind::Consume(_) | MKind::GCount => {
                b.block(m.body - 1, 2);
                b.final_return(2);
            }
            MKind::Bump(fi) => {
                b.param(0, PTy::Sc(fsc(fi)));
                b.block(m.body - 1, 2);
                let n = fname(fi);
                b.push("        self.");
                b.push(n);
                b.push(" = self.");
                b.push(n);
                b.push(" +% p0;\n");
            }
            MKind::RefGet(fi) => {
                b.block(m.body - 1, 2);
                b.push("        return &self.");
                b.push(fname(fi));
                b.push(";\n");
            }
            MKind::Mix(fi) => {
                b.param(0, PTy::Ref(st));
                b.block(m.body - 1, 2);
                let n = fname(fi);
                b.push("        return self.");
                b.push(n);
                b.push(if fsc(fi).is_int() { " +% p0." } else { " + p0." });
                b.push(n);
                b.push(";\n");
            }
            MKind::GGet => {
                b.block(m.body - 1, 2);
                b.push("        return &self.");
                b.push(fname(0));
                b.push(";\n");
            }
            MKind::GPut => {
                b.param(0, PTy::T);
                b.block(m.body.saturating_sub(2), 2);
                b.push("        self.");
                b.push(fname(0));
                b.push(" = p0;\n        self.");
                b.push(fname(1));
                b.push(" = self.");
                b.push(fname(1));
                b.push(" +% 1;\n");
            }
        }
        self.out.push_str("    }\n");
    }

    fn trait_item(&mut self, t: &'a TraitDef) {
        let _ = writeln!(self.out, "pub trait {} {{", t.name);
        for m in &t.methods {
            let _ = write!(self.out, "    fn {}(&self", m.name);
            if let Some(a) = m.arg {
                let _ = write!(self.out, ", p0: {}", a.name());
            }
            let _ = writeln!(self.out, ") -> {};", m.ret.name());
        }
        self.out.push_str("}\n");
    }

    fn timpl_item(&mut self, ti: &'a TraitImpl) {
        let p = self.p;
        let t = &p.traits[ti.tr as usize];
        let _ = writeln!(self.out, "impl {} for {} {{", t.name, p.structs[ti.target as usize].name);
        for (m, &lines) in t.methods.iter().zip(&ti.bodies) {
            let _ = write!(self.out, "    fn {}(&self", m.name);
            if let Some(a) = m.arg {
                let _ = write!(self.out, ", p0: {}", a.name());
            }
            let _ = writeln!(self.out, ") -> {} {{", m.ret.name());
            let mut b = self.body(0, RetCtx::Sc(m.ret));
            b.self_param(ti.target, How::SelfRef);
            if let Some(a) = m.arg {
                b.param(0, PTy::Sc(a));
            }
            b.block(lines - 1, 2);
            b.final_return(2);
            self.out.push_str("    }\n");
        }
        self.out.push_str("}\n");
    }

    fn const_item(&mut self, c: &'a ConstDef) {
        let _ = write!(self.out, "pub const {}: ", c.name);
        match c.alias {
            Some(a) => self.out.push_str(&self.p.aliases[a as usize].name),
            None => self.out.push_str(c.ty.name()),
        }
        let (a, b) = (1 + self.r.below(9), 1 + self.r.below(9));
        let _ = match self.r.below(4) {
            0 => writeln!(self.out, " = {a} * {b};"),
            1 => writeln!(self.out, " = {a} + {b};"),
            2 => writeln!(self.out, " = 0x{:x};", a * 16 + b),
            _ => writeln!(self.out, " = {};", a * 10 + b),
        };
    }
}

/// `src/main.stv`: imports every module no other module imports and calls its `run_<k>`.
pub fn main_text(plans: &[ModPlan], sinks: &[u32], pad: u32, lines: u64, seed: u64) -> String {
    let mut o = String::with_capacity(64 * (sinks.len() + pad as usize) + 256);
    let _ = writeln!(o, "// Stave corpus root (generated by gen-corpus: --lines {lines} --seed {seed})");
    o.push_str("import std.io;\n");
    for &k in sinks {
        let _ = writeln!(o, "import {} as m{k};", plans[k as usize].dotted());
    }
    o.push_str("\nfn main() -> i32 {\n    let mut acc: u64 = 0;\n");
    for &k in sinks {
        let _ = writeln!(o, "    acc = acc +% m{k}.run_{k}();");
    }
    let mut r = Rng::derive(seed, u64::MAX, 5);
    for _ in 0..pad {
        let v = r.below(100);
        let _ = writeln!(o, "    acc = acc +% {v};");
    }
    o.push_str("    io.print(f\"acc = {acc}\\n\");\n    return 0;\n}\n");
    o
}

/// `stave.toml`.
pub fn manifest() -> &'static str {
    "name = \"corpus\"\nkind = \"bin\"\nversion = \"0.1.0\"\n"
}
